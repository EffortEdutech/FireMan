// Generates the SQL migration that seeds the fire-system report template catalogue
// for every organisation. Run with Node 22.18+ (native TypeScript type stripping):
//   node scripts/generate-system-report-template-migration.mjs > supabase/migrations/<timestamp>_fire_system_report_templates.sql
// Review the output before applying it to any hosted database.
import { buildSystemReportCatalog } from "../lib/reports/system-report-catalog.ts";

const templates = buildSystemReportCatalog();

function sqlText(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = templates
  .map((template) => {
    const layout = JSON.stringify(template.layout);
    if (layout.includes("$catalog$")) throw new Error(`Template ${template.slug} contains the SQL delimiter.`);
    return `    (${sqlText(template.slug)}, ${sqlText(template.name)}, ${sqlText(template.description)}, $catalog$${layout}$catalog$::jsonb)`;
  })
  .join(",\n");

process.stdout.write(`-- Fire-system report template catalogue (${templates.length} templates).
-- Generated by scripts/generate-system-report-template-migration.mjs from lib/reports/system-report-catalog.ts.
-- Adds one set of per-system and combined (per-visit) templates to every organisation.
-- Idempotent: existing slugs are left untouched. Does not change reports or existing templates.

with catalog (slug, name, description, layout) as (
  values
${rows}
)
insert into public.report_templates (
  organisation_id,
  name,
  slug,
  description,
  report_type,
  layout,
  active,
  is_default
)
select
  o.id,
  c.name,
  c.slug,
  c.description,
  'MAINTENANCE'::public.report_type,
  c.layout,
  true,
  false
from public.organisations o
cross join catalog c
on conflict (organisation_id, slug) do nothing;
`);
